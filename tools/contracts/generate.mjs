// An unquoted comma in a flow-style description splits it into stray null
// keys, which strict OpenAPI parsers such as swift-openapi-generator's refuse.
;(function refuseNulls(node, path) {
  if (node === null) throw new Error(`Null value at ${path}: quote the description it was split from`)
  if (typeof node === 'object') for (const [k, v] of Object.entries(node)) refuseNulls(v, `${path}/${k}`)
})(document, '')
