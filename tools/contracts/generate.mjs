const ios = { openapi: document.openapi, info: { ...document.info, title: 'Reverb API (iOS subset)' }, servers: document.servers, paths: {}, components: {} }
const wanted = new Set()
function collectRefs(node) {
  if (Array.isArray(node)) return node.forEach(collectRefs)
  if (!node || typeof node !== 'object') return
  for (const [key, value] of Object.entries(node)) {
    if (key === '$ref' && typeof value === 'string') {
      const ref = value.replace('#/components/', '')
      if (!wanted.has(ref)) {
        wanted.add(ref)
        const [kind, name] = ref.split('/')
        const target = document.components[kind]?.[name]
        if (!target) throw new Error(`Unresolved reference: ${value}`)
        collectRefs(target)
      }
    } else collectRefs(value)
  }
}
for (const [path, methods] of Object.entries(iosOperations)) {
  if (!document.paths[path]) throw new Error(`iOS operation path is gone: ${path}`)
  ios.paths[path] = {}
  for (const [method, operationId] of Object.entries(methods)) {
    const op = document.paths[path][method]
    if (!op) throw new Error(`iOS operation is gone: ${method.toUpperCase()} ${path}`)
    ios.paths[path][method] = { operationId, ...op }
    collectRefs(op)
  }
}
for (const ref of [...wanted].sort()) {
  const [kind, name] = ref.split('/')
  ;(ios.components[kind] ??= {})[name] = document.components[kind][name]
}
